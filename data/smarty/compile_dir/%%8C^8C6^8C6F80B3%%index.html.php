				u_i.style.width=w_end_num+'px';
				u_i.style.height=h_end_num+'px';
				$('#image_w').val(w_end_num);
				$('#image_h').val(h_end_num);
				//相对上边剧中的值
				var top_v	=	(284-h_end_num)/2;
				//相对左边剧中的值
				var left_m	=	(214-w_end_num)/2;
				u_i.style.marginTop=top_v+'px';
				u_i.style.marginLeft=left_m+'px';
				$('#move_up_down').val(top_v);
				$('#move_left_right').val(left_m);
				//alert(aaaa);
				if(m_v!=''){//计算上下移动
					var a_m_v	=	m_v*average_num;
					if((top_v-a_m_v)<0){
						alert('上下移动距离超出！');
					}else{
						u_i.style.marginTop=top_v-m_v*average_num+'px';
						$('#move_up_down').val(a_m_v);	
					}
				}else{
					$('#move_up_down').val(0);
				} 
				if(m_t!=''){//计算左右移动
					var a_m_t	=	m_t*average_num;
					if((left_m-a_m_t)<0){
						alert('左右移动距离超出！');
					}else{
						u_i.style.marginLeft=left_m-m_t*average_num+'px';	
						$('#move_left_right').val(a_m_t);
					}
				}else{
					$('#move_left_right').val(0);	
				} 
				$('#save_image').css('display','block');
			}else{
				alert('图片尺寸不能超过规定且不能为空！');	
			}	
		}
	});
	
