function get_clothes_size(){
	var sex	=	$('#sex').val();
	$.ajax({
		url:'<?php echo $this->_tpl_vars['__ROOT__']; ?>
/tshirt_design/get_clothes_size',//通过Ajax取数据的目标页面
		data:{"sex":sex},
		type:'post',//方法，还可以是"post"
		dataType:'json',//数据类型，还有其它的，详见jQuery手册
		success:function(locals)//成功后执行的语句，这里是一个函数，"locals"是返回的数据
		{	
			if(locals!=1){
				$('#clothes_size').html('');
				var size_info	=	'<option value="">请选择</option>';
				for(var i=0;i<locals.size.length;i++){
					size_info+='<option value="'+locals.size_num[i]+'">'+locals.size[i]+'</option>';
				}
				$('#clothes_size').html(size_info);
			}else{
				$('#clothes_size').html('');	
			}
		}	
	});	
}
//选择规格
function get_size_number(){
	var w_num	=	$('#clothes_size').val();//衣服的尺寸
	if(w_num!=''){
		$('#err_w').html('图片最宽'+w_num+'CM');
		var h_num	=	(w_num/214*284).toFixed(2)	;
		$('#err_h').html('图片最高'+h_num+'CM');
	}
}


